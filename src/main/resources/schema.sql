-- Esquema de la base de datos H2 del Sistema de Inventario POS.
-- La aplicación lo ejecuta en cada arranque, por eso cada sentencia usa IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS usuarios (
    usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) DEFAULT 'VENDEDOR' NOT NULL,
    activo BOOLEAN DEFAULT TRUE,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ultimo_login TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categorias (
    categoria_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(1000),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS productos (
    producto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) UNIQUE NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(1000),
    precio_compra DECIMAL(10, 2) NOT NULL,
    precio_venta DECIMAL(10, 2) NOT NULL,
    stock INTEGER DEFAULT 0 NOT NULL CHECK (stock >= 0),
    stock_minimo INTEGER DEFAULT 5,
    categoria_id BIGINT REFERENCES categorias(categoria_id),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_productos_nombre ON productos(nombre);
CREATE INDEX IF NOT EXISTS idx_productos_categoria ON productos(categoria_id);

-- cedula guarda el RFC del cliente (se conserva el nombre de la columna)
CREATE TABLE IF NOT EXISTS clientes (
    cliente_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    cedula VARCHAR(20) UNIQUE NOT NULL,
    email VARCHAR(100),
    telefono VARCHAR(20),
    direccion VARCHAR(500),
    ciudad VARCHAR(100),
    estado VARCHAR(50),
    saldo_credito DECIMAL(10, 2) DEFAULT 0,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_clientes_nombre ON clientes(nombre);

-- rif guarda el RFC del proveedor (se conserva el nombre de la columna)
CREATE TABLE IF NOT EXISTS proveedores (
    proveedor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    rif VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(100),
    telefono VARCHAR(20),
    direccion VARCHAR(500),
    ciudad VARCHAR(100),
    condiciones_pago VARCHAR(100),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_proveedores_nombre ON proveedores(nombre);

CREATE TABLE IF NOT EXISTS ventas (
    venta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(usuario_id),
    cliente_id BIGINT REFERENCES clientes(cliente_id),
    subtotal DECIMAL(10, 2) NOT NULL,
    descuento DECIMAL(10, 2) DEFAULT 0 NOT NULL,
    total DECIMAL(10, 2) NOT NULL,
    metodo_pago VARCHAR(50),
    estado VARCHAR(20) DEFAULT 'COMPLETADA',
    observaciones VARCHAR(1000),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ventas_cliente ON ventas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON ventas(fecha_creacion);

CREATE TABLE IF NOT EXISTS detalles_venta (
    detalle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES ventas(venta_id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(producto_id),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10, 2) NOT NULL,
    -- precio de compra al momento de la venta, para calcular la ganancia real
    costo_unitario DECIMAL(10, 2) DEFAULT 0 NOT NULL,
    subtotal DECIMAL(10, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_detalles_venta_venta ON detalles_venta(venta_id);

-- tipo: ENTRADA, SALIDA o AJUSTE. En AJUSTE la cantidad es la diferencia (puede ser negativa).
-- referencia_id: número de venta cuando el movimiento lo generó una venta o su anulación.
CREATE TABLE IF NOT EXISTS movimientos_inventario (
    movimiento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES productos(producto_id),
    tipo VARCHAR(20) NOT NULL,
    cantidad INTEGER NOT NULL,
    referencia_id BIGINT,
    proveedor_id BIGINT REFERENCES proveedores(proveedor_id),
    descripcion VARCHAR(1000),
    usuario_id BIGINT REFERENCES usuarios(usuario_id),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_movimientos_producto ON movimientos_inventario(producto_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_fecha ON movimientos_inventario(fecha_creacion);

CREATE TABLE IF NOT EXISTS cortes_caja (
    corte_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(usuario_id),
    fecha DATE NOT NULL,
    numero_ventas INTEGER NOT NULL,
    total_vendido DECIMAL(10, 2) NOT NULL,
    ventas_efectivo DECIMAL(10, 2) NOT NULL,
    fondo_inicial DECIMAL(10, 2) NOT NULL,
    efectivo_contado DECIMAL(10, 2) NOT NULL,
    -- efectivo_contado - (fondo_inicial + ventas_efectivo); negativo = faltante
    diferencia DECIMAL(10, 2) NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cortes_fecha ON cortes_caja(fecha);

